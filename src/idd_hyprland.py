#!/usr/bin/python3
"""Configure Idd's NVIDIA monitor in the current user's Hyprland session."""

import argparse
from datetime import datetime, timezone
import json
import math
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time
import uuid


class HyprlandError(Exception):
    pass


def validate_settings(settings):
    required = {"connector", "mode", "position", "scale", "format"}
    if not isinstance(settings, dict) or not required.issubset(settings):
        raise HyprlandError("Hyprland settings need connector, mode, position, scale, and format.")
    if not isinstance(settings["connector"], str) or not re.fullmatch(r"(?:DP|HDMI-A|DVI-D)-[1-9][0-9]*", settings["connector"]):
        raise HyprlandError("Select a connector such as DP-1 or HDMI-A-1.")
    mode = settings.get("mode", "preferred")
    if not isinstance(mode, str) or not re.fullmatch(r"preferred|[1-9][0-9]{2,4}x[1-9][0-9]{2,4}@[0-9]+(?:\.[0-9]+)?", mode):
        raise HyprlandError("Mode must be preferred or WIDTHxHEIGHT@HZ, for example 2560x1440@144.")
    if mode != "preferred" and not 1 <= float(mode.split("@")[1]) <= 1000:
        raise HyprlandError("Invalid refresh rate.")
    position = settings.get("position", "auto")
    if not isinstance(position, str) or not re.fullmatch(r"auto|-?[0-9]+x-?[0-9]+", position):
        raise HyprlandError("Position must be auto or XxY, for example 1920x0.")
    scale = settings.get("scale", 1)
    if type(scale) not in (int, float) or not math.isfinite(scale) or not 0.25 <= scale <= 4:
        raise HyprlandError("Scale must be a finite number between 0.25 and 4.")
    if settings.get("format") not in ("hyprlang", "lua"):
        raise HyprlandError("Configuration format must be hyprlang or lua.")
    if "transform" in settings and (type(settings["transform"]) is not int or not 0 <= settings["transform"] <= 7):
        raise HyprlandError("Transform must be an integer between 0 and 7.")


def lua_string(value):
    return json.dumps(value, ensure_ascii=False)


def monitor_rule(settings, disabled=False):
    connector = settings["connector"]
    if settings["format"] == "lua":
        if disabled:
            return "hl.monitor({ output = " + lua_string(connector) + ", disabled = true })"
        return ("hl.monitor({ output = " + lua_string(connector) + ", mode = " + lua_string(settings["mode"])
                + ", position = " + lua_string(settings["position"]) + f", scale = {settings['scale']:g}"
                + (f", transform = {settings['transform']}" if "transform" in settings else "") + " })")
    if disabled:
        return connector + ",disable"
    return (f"{connector},{settings['mode']},{settings['position']},{settings['scale']:g}"
            + (f",transform,{settings['transform']}" if "transform" in settings else ""))


def include_content(settings):
    comment = "--" if settings["format"] == "lua" else "#"
    rule = monitor_rule(settings)
    return f"{comment} Generated by idd hyprland. Edit ~/.config/idd/hyprland.json and run idd hyprland apply.\n" + (
        rule if settings["format"] == "lua" else "monitor = " + rule) + "\n"


def managed_config(text, language, include=None):
    pattern = r"(?ms)^(?:#|--) BEGIN IDD HYPRLAND\r?\n.*?^(?:#|--) END IDD HYPRLAND[^\S\r\n]*(?:\r?\n|$)"
    cleaned = re.sub(pattern, "", text)
    if re.search(r"^(?:#|--) (?:BEGIN|END) IDD HYPRLAND", cleaned, re.M):
        raise HyprlandError("Incomplete Idd markers in the Hyprland config; refusing to rewrite it.")
    if include is None:
        return cleaned
    comment = "--" if language == "lua" else "#"
    if language == "lua":
        # Hyprland's require tracks included files and isolates their errors.
        source = "require(" + lua_string(str(include.with_suffix(""))) + ")"
    else:
        if any(char in str(include) for char in "\r\n#$"):
            raise HyprlandError("Hyprlang source path cannot contain newlines, #, or $.")
        source = "source = " + str(include)
    return cleaned.rstrip() + f"\n\n{comment} BEGIN IDD HYPRLAND\n{source}\n{comment} END IDD HYPRLAND\n"


def atomic_text(path, text, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp-" + uuid.uuid4().hex)
    try:
        with temp.open("x", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.chmod(temp, mode)
        os.replace(temp, path)
    finally:
        temp.unlink(missing_ok=True)


class Hyprctl:
    def __init__(self, instance=None, executable=None):
        self.executable = executable or shutil.which("hyprctl")
        if not self.executable:
            raise HyprlandError("hyprctl is missing. Run this command in the guest with Hyprland installed.")
        self.instance = instance or os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")
        if not self.instance:
            raise HyprlandError("Run inside a Hyprland terminal, or select --instance from hyprctl instances.")
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", self.instance) or self.instance.startswith("-"):
            raise HyprlandError("Invalid Hyprland instance identifier.")

    def run(self, *args):
        try:
            r = subprocess.run([self.executable, "-i", self.instance, *args], capture_output=True,
                               text=True, errors="replace", timeout=5)
        except (OSError, subprocess.TimeoutExpired) as error:
            raise HyprlandError(f"Cannot contact Hyprland: {error}")
        if r.returncode:
            raise HyprlandError((r.stderr or r.stdout).strip()[:2000] or "hyprctl failed")
        return r.stdout.strip()

    def monitors(self):
        try:
            data = json.loads(self.run("-j", "monitors", "all"))
        except ValueError:
            raise HyprlandError("Hyprland did not return a JSON monitor list.")
        if not isinstance(data, list) or any(not isinstance(m, dict) for m in data):
            raise HyprlandError("Unexpected Hyprland monitor response.")
        return data

    def set_monitor(self, settings, disabled=False):
        rule = monitor_rule(settings, disabled)
        reply = self.run("eval", rule) if settings["format"] == "lua" else self.run("keyword", "monitor", rule)
        if reply.lower() != "ok":
            raise HyprlandError("Hyprland rejected the monitor rule: " + reply[:2000])


def idd_monitor(monitor):
    return monitor.get("model") == "Idd NVIDIA" or "Idd NVIDIA" in str(monitor.get("description", ""))


def select_monitor(monitors, connector=None):
    matches = [m for m in monitors if idd_monitor(m) and (connector is None or m.get("name") == connector)]
    if len(matches) != 1:
        raise HyprlandError("Hyprland must see one Idd NVIDIA monitor. Start idd-display.service first; "
                            "use --connector if several are present. If it is absent, check NVIDIA/AQ_DRM_DEVICES.")
    return matches[0]


def check_mode(monitor, mode):
    if mode == "preferred":
        return
    width, height, refresh = (float(value) for value in re.split(r"[x@]", mode))
    available = monitor.get("availableModes", [])
    if not isinstance(available, list):
        available = []
    for candidate in available:
        match = re.fullmatch(r"([0-9]+)x([0-9]+)@([0-9.]+)(?:Hz)?", str(candidate))
        if match and float(match[1]) == width and float(match[2]) == height and abs(float(match[3]) - refresh) <= 0.25:
            return
    raise HyprlandError(f"Hyprland does not advertise {mode} on {monitor['name']}. "
                        "Add it to /etc/idd/modes.json and run sudo idd apply first, or select an available rate.")


def restored_settings(monitor, language):
    if monitor.get("disabled") or not monitor.get("width") or not monitor.get("height"):
        return {"connector": monitor["name"], "format": language}, True
    return {"connector": monitor["name"], "format": language,
            "mode": f"{monitor['width']}x{monitor['height']}@{monitor['refreshRate']:g}",
            "position": f"{monitor.get('x', 0)}x{monitor.get('y', 0)}", "scale": monitor.get("scale", 1),
            "transform": monitor.get("transform", 0)}, False


def verify_monitor(client, settings, wait=4):
    deadline = time.monotonic() + wait
    while True:
        monitor = next((m for m in client.monitors() if m.get("name") == settings["connector"]), None)
        matched = bool(monitor) and not monitor.get("disabled", False) and bool(monitor.get("width"))
        if matched and settings["mode"] != "preferred":
            width, height, refresh = (float(value) for value in re.split(r"[x@]", settings["mode"]))
            matched = (monitor.get("width") == width and monitor.get("height") == height
                       and abs(monitor.get("refreshRate", 0) - refresh) <= 0.25)
        if matched and abs(monitor.get("scale", 0) - settings["scale"]) <= 0.001:
            if settings["position"] == "auto" or tuple(int(v) for v in settings["position"].split("x")) == (monitor.get("x"), monitor.get("y")):
                return monitor
        if time.monotonic() >= deadline:
            raise HyprlandError("Hyprland did not enable the requested mode/scale; restoring previous settings.")
        time.sleep(0.5)


class Integration:
    def __init__(self, root=None):
        self.root = root or Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
        if not self.root.is_absolute():
            raise HyprlandError("XDG_CONFIG_HOME must be an absolute directory.")
        self.directory = self.root / "idd"
        self.profile = self.directory / "hyprland.json"

    def config_path(self, explicit=None):
        if explicit:
            path = Path(explicit).expanduser().resolve()
            if not path.is_file():
                raise HyprlandError(f"Hyprland config does not exist: {path}")
            return path
        candidates = [self.root / "hypr" / name for name in ("hyprland.lua", "hyprland.conf")]
        found = [path for path in candidates if path.is_file()]
        if len(found) != 1:
            raise HyprlandError("Select the running Hyprland config with --config (none or several defaults exist).")
        return found[0].resolve()

    def load(self):
        settings = json.loads(self.profile.read_text())
        validate_settings(settings)
        if not isinstance(settings.get("config"), str) or not Path(settings["config"]).is_absolute():
            raise HyprlandError("The saved Hyprland config must be an absolute path.")
        return settings

    def apply(self, client, settings, wait=4):
        validate_settings(settings)
        monitor = select_monitor(client.monitors(), settings["connector"])
        check_mode(monitor, settings["mode"])
        main = self.config_path(settings["config"])
        include = self.directory / ("hyprland-monitor.lua" if settings["format"] == "lua" else "hyprland-monitor.conf")
        text = main.read_text(encoding="utf-8")
        new_text = managed_config(text, settings["format"], include)
        errors_before = client.run("configerrors")
        if errors_before:
            raise HyprlandError("Fix existing Hyprland config errors before applying Idd settings: " + errors_before[:2000])
        files = [main, include, self.profile]
        previous = {p: (p.read_bytes(), p.stat().st_mode & 0o777) if p.exists() else None for p in files}
        if new_text != text:
            backup = main.with_name(main.name + ".idd-backup-" + datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S") + "-" + uuid.uuid4().hex[:6])
            backup.write_bytes(main.read_bytes())
            os.chmod(backup, previous[main][1])
        try:
            atomic_text(include, include_content(settings))
            atomic_text(self.profile, json.dumps(settings, indent=2) + "\n")
            if new_text != text:
                atomic_text(main, new_text, previous[main][1])
            client.run("reload")
            errors_after = client.run("configerrors")
            if errors_after and errors_after != errors_before:
                raise HyprlandError("Hyprland config error: " + errors_after[:2000])
            client.set_monitor(settings)
            return verify_monitor(client, settings, wait)
        except (OSError, ValueError, TypeError, KeyError, HyprlandError, KeyboardInterrupt) as error:
            failures = []
            for path, content in previous.items():
                try:
                    if content is None:
                        path.unlink(missing_ok=True)
                    else:
                        atomic_text(path, content[0].decode("utf-8"), content[1])
                except OSError as restore_error:
                    failures.append(str(restore_error))
            try:
                client.run("reload")
                old, disabled = restored_settings(monitor, settings["format"])
                client.set_monitor(old, disabled)
            except (OSError, ValueError, TypeError, KeyError, HyprlandError) as restore_error:
                failures.append(str(restore_error))
            detail = "; recovery needs attention: " + "; ".join(failures) if failures else "; previous files and monitor rule restored"
            raise HyprlandError(str(error) + detail)

    def remove(self, client):
        settings = self.load()
        main = self.config_path(settings["config"])
        text = main.read_text(encoding="utf-8")
        original = {main: text, self.profile: self.profile.read_text(encoding="utf-8")}
        include = self.directory / ("hyprland-monitor.lua" if settings["format"] == "lua" else "hyprland-monitor.conf")
        if include.exists():
            original[include] = include.read_text(encoding="utf-8")
        errors_before = client.run("configerrors")
        try:
            atomic_text(main, managed_config(text, settings["format"]), main.stat().st_mode & 0o777)
            client.run("reload")
            errors_after = client.run("configerrors")
            if errors_after and errors_after != errors_before:
                raise HyprlandError(errors_after)
            include.unlink(missing_ok=True)
            self.profile.unlink()
        except (OSError, HyprlandError) as error:
            for path, contents in original.items():
                atomic_text(path, contents)
            client.run("reload")
            raise HyprlandError("Could not remove integration; restored its files: " + str(error))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest="command", required=True)
    for command in ("setup", "apply", "status", "remove"):
        p = subs.add_parser(command)
        p.add_argument("--instance", help="Hyprland instance; defaults to the current session")
        if command == "setup":
            p.add_argument("--connector", help="Auto-detect Idd NVIDIA by its EDID model")
            p.add_argument("--mode", default="preferred", help="preferred or WIDTHxHEIGHT@HZ")
            p.add_argument("--position", default="auto", help="auto or XxY (negative example: --position=-1920x0)")
            p.add_argument("--scale", type=float, default=1)
            p.add_argument("--config", type=Path, help="Your actual Hyprland main config")
            p.add_argument("--format", choices=("auto", "hyprlang", "lua"), default="auto")
    args = parser.parse_args(argv)
    try:
        if sys.platform != "linux":
            raise HyprlandError("Run inside the Linux guest's Hyprland session.")
        if os.geteuid() == 0:
            raise HyprlandError("Run idd hyprland as the logged-in desktop user, without sudo.")
        client, integration = Hyprctl(args.instance), Integration()
        if args.command == "setup":
            monitor = select_monitor(client.monitors(), args.connector)
            config = integration.config_path(args.config)
            language = args.format if args.format != "auto" else ("lua" if config.suffix == ".lua" else "hyprlang")
            settings = {"connector": monitor["name"], "mode": args.mode, "position": args.position,
                        "scale": args.scale, "format": language, "config": str(config)}
            result = integration.apply(client, settings)
        elif args.command == "apply":
            result = integration.apply(client, integration.load())
        elif args.command == "remove":
            integration.remove(client)
            result = {"integration_removed": True, "guest_display_service_changed": False}
        else:
            result = {"profile": str(integration.profile),
                      "settings": integration.load() if integration.profile.exists() else None,
                      "monitors": [m for m in client.monitors() if idd_monitor(m)]}
        print(json.dumps(result, indent=2))
        return 0
    except (OSError, ValueError, TypeError, HyprlandError) as error:
        print(f"idd hyprland: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
